package com.example.app_spring.ai;

import org.springframework.stereotype.Component;

import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;

/**
 * 小灵 · 本地规则问答引擎
 * ---------------------------------------------------------------------------
 * 定位：康复训练辅助的「规则问答」，不接大模型、不依赖网络，保证比赛现场可用。
 * 后续如需接入大模型，只需把 {@link #reply} 换成调用外部 API，接口与前端无需改动。
 *
 * 安全边界（重要）：
 *  - 不做任何诊断结论，不给用药/治疗方案；
 *  - 涉及疼痛、麻木、明显不对称等情况，一律建议线下就医/咨询专业康复师；
 *  - 所有建议均为通用训练提示。
 */
@Component
public class AiRuleEngine {

    /** 一条规则：命中任一关键词即采用该回答 */
    private record Rule(List<String> keys, String answer) {}

    private static final List<Rule> RULES = List.of(
        new Rule(List.of("臀桥"), """
            臀桥这样练（每日 1~2 组）：
            1) 仰卧屈膝，双脚与髋同宽，脚跟离臀部约一掌；
            2) 呼气时收紧臀部把髋抬起到「肩—髋—膝」接近一条直线，顶峰保持 1~2 秒；
            3) 吸气缓慢下放，不要让腰先塌下去。
            建议每组 8~15 次，动作全程匀速，宁少勿快。"""),

        new Rule(List.of("猫式", "猫牛"), """
            猫式伸展这样做：
            1) 四点跪姿，手腕在肩正下方，膝盖在髋正下方；
            2) 呼气时拱背低头（像猫伸懒腰），吸气时放松回落；
            3) 每个方向停留 2~3 秒，做 8~10 次。
            重点在「慢」，靠呼吸带动脊柱，不要用手臂硬撑。"""),

        new Rule(List.of("侧平板", "侧支撑"), """
            侧平板要点：
            1) 手肘在肩正下方，身体从头到脚踝保持一条直线；
            2) 髋部不要下沉，也不要耸肩；
            3) 先从每侧 15~20 秒开始，逐步加到 30~45 秒。
            如果腰部不舒服，先做屈膝版本降低难度。"""),

        new Rule(List.of("燕飞", "小燕飞"), """
            燕飞（俯卧挺身）要点：
            1) 俯卧，双手放在体侧或前伸；
            2) 同时抬起上半身与双腿，感受背部发力，注意不要猛甩；
            3) 顶峰保持 1~2 秒后缓慢放下，做 8~12 次。
            抬起的幅度不必很大，颈部保持中立、不要过度后仰。"""),

        new Rule(List.of("今天", "计划", "练什么", "安排", "一周", "每天"), """
            给你一份通用的一周安排（可按体力增减）：
            · 周一 / 周四：臀桥 3 组 × 10~15 次 + 猫式 8 次
            · 周二 / 周五：侧平板 每侧 3 组 × 20~30 秒
            · 周三 / 周六：燕飞 3 组 × 8~12 次 + 拉伸放松
            · 周日：休息或散步
            每次训练 15~25 分钟即可，训练中出现疼痛就立即停止。"""),

        new Rule(List.of("脊柱", "侧弯", "驼背", "含胸", "高低肩", "体态"), """
            关于体态和脊柱，先说清楚：App 里的体态分析属于「训练辅助参考」，不是医学诊断。
            日常可以这样做：
            1) 避免长时间低头和单侧背包；
            2) 每天做猫式伸展 + 臀桥，帮助放松和稳定核心；
            3) 每 40 分钟起身活动 2~3 分钟。
            如果发现明显的高低肩、背部不对称，或伴随疼痛麻木，请到医院做专业影像检查。"""),

        new Rule(List.of("疼", "痛", "麻", "不舒服", "酸"), """
            训练中出现疼痛、麻木或明显不适，请先停下来，不要硬撑。
            · 轻微肌肉酸胀：休息 1~2 天，做温和拉伸即可；
            · 关节疼痛、放射痛或麻木：停止训练，建议尽快线下就医评估。
            App 只能提供通用训练提示，不能替代医生或康复师的诊断。"""),

        new Rule(List.of("呼吸"), """
            呼吸配合要点：发力时呼气、还原时吸气，全程不要憋气。
            以臀桥为例：抬起髋部时呼气，落回时吸气，节奏保持均匀。"""),

        new Rule(List.of("多久", "几次", "频率", "时长", "组数"), """
            通用训练频率建议：
            · 每周 3~5 次，每次 15~25 分钟；
            · 每个动作 2~3 组，组间休息 30~60 秒；
            · 以「动作能保持标准」为强度上限，宁可减少次数也不要变形。
            刚开始请从最小量做起，第二周再逐步增加。"""),

        new Rule(List.of("你好", "hi", "hello", "在吗", "你是谁"), """
            你好，我是小灵，负责给你康复训练方面的通用建议。
            你可以问我：今天该练什么、臀桥怎么做、训练多久合适、动作疼了怎么办。""")
    );

    private static final String FALLBACK = """
        我可以聊这些训练话题：
        · 「我今天应该做哪些训练？」——给你一周安排
        · 「臀桥怎么做？」——动作要领
        · 「猫式 / 侧平板 / 燕飞」——各自动作要点
        · 「训练多久、做几组」——频率建议
        · 「练的时候疼怎么办」——安全提示
        换个说法再问一次就行。""";

    /**
     * 根据用户问题匹配回答。
     *
     * @return answer(回答文本) 与 matched(命中的关键词，未命中为 null)
     */
    public Map<String, Object> reply(String question) {
        final String q = question == null ? "" : question.trim().toLowerCase();
        Map<String, Object> out = new LinkedHashMap<>();
        if (q.isEmpty()) {
            out.put("answer", FALLBACK);
            out.put("matched", null);
            return out;
        }
        for (Rule r : RULES) {
            for (String k : r.keys()) {
                if (q.contains(k.toLowerCase())) {
                    out.put("answer", r.answer());
                    out.put("matched", k);
                    return out;
                }
            }
        }
        out.put("answer", FALLBACK);
        out.put("matched", null);
        return out;
    }
}